import assert from "node:assert/strict";
import {pathToFileURL} from "node:url";
import https from "node:https";
import {mkdtempSync,readFileSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {execFileSync} from "node:child_process";
const modulePath = process.env.ATTRIBUTION_PLAYWRIGHT_MODULE;
const {chromium} = modulePath ? await import(pathToFileURL(modulePath).href) : await import("playwright");
const origin = process.env.ATTRIBUTION_BROWSER_ORIGIN;
let browser, page, merchant, certificateDir, stage = "launch";
try {
  certificateDir = mkdtempSync(join(tmpdir(),"as-browser-"));
  execFileSync("openssl",["req","-x509","-newkey","rsa:2048","-nodes","-keyout",join(certificateDir,"key.pem"),"-out",join(certificateDir,"cert.pem"),"-days","1","-subj","/CN=shop.merchant.com"],{stdio:"ignore"});
  merchant = https.createServer({key:readFileSync(join(certificateDir,"key.pem")),cert:readFileSync(join(certificateDir,"cert.pem"))},(_request,response) => {
    response.writeHead(200,{"Content-Type":"text/html"}); response.end("<!doctype html><title>Merchant fixture</title><h1>Product</h1>");
  });
  await new Promise(resolve => merchant.listen(0,"127.0.0.1",resolve));
  browser = await chromium.launch({headless:true,args:[`--host-resolver-rules=MAP shop.merchant.com 127.0.0.1:${merchant.address().port}`,"--no-proxy-server"]});
  const context = await browser.newContext({ignoreHTTPSErrors:true});
  await context.addCookies([{name:"__Host-attribution",value:process.env.ATTRIBUTION_BROWSER_SESSION,domain:new URL(origin).hostname,path:"/",secure:true,httpOnly:true,sameSite:"Lax"}]);
  page = await context.newPage();
  await page.goto(`${origin}/settings?company_id=${process.env.ATTRIBUTION_BROWSER_COMPANY}`);
  stage = "accessible store creation";
  const store = page.locator("#store-create");
  await store.getByLabel("Store name",{exact:true}).fill('Shop <script>window.injected=true</script>');
  await store.getByLabel("Timezone",{exact:true}).fill("Europe/Berlin");
  await store.getByRole("button",{name:"Add store",exact:true}).focus();
  await page.keyboard.press("Enter");
  await page.locator("#stores-list button").first().waitFor();
  await page.locator("#stores-list button").first().click();
  assert.equal(await page.evaluate(() => window.injected),undefined);
  stage = "domain challenge and real DNS verification";
  await page.getByLabel("Exact host",{exact:true}).fill("shop.merchant.com");
  await page.getByRole("button",{name:"Get DNS challenge",exact:true}).click();
  await page.getByRole("heading",{name:"Publish this DNS TXT record"}).waitFor();
  assert.ok((await page.locator("#setup-result").innerText()).includes("_attribution.shop.merchant.com"));
  await page.evaluate(() => fetch("/fixture/publish-dns",{method:"POST"}));
  await page.getByRole("button",{name:"Verify domain",exact:true}).click();
  await page.waitForFunction(() => document.getElementById("domains-list").textContent.includes(": verified"));
  stage = "campaign/ad/link forms and stable retry";
  const campaign = page.locator("#campaign-create");
  await campaign.getByLabel("Campaign name",{exact:true}).fill('Summer <script>window.injected=true</script>');
  await campaign.getByRole("button",{name:"Add campaign",exact:true}).click();
  await page.waitForFunction(() => document.querySelector("#ad-campaign").options.length === 2);
  const ad = page.locator("#ad-create");
  await ad.getByLabel("Campaign",{exact:true}).selectOption({index:1});
  await ad.getByLabel("Ad name",{exact:true}).fill("Summer ad");
  await ad.getByLabel("Advertised product reference (optional)",{exact:true}).fill("P1");
  await ad.getByRole("button",{name:"Add ad",exact:true}).click();
  await page.waitForFunction(() => document.querySelector("#link-ad").options.length === 2);
  let initial, retries = 0;
  await page.route("**/v1/links", async route => {
    const request = route.request();
    if (request.method() !== "POST") return route.continue();
    const identity = {key:request.headers()["idempotency-key"],time:request.headers()["idempotency-created-at"],body:request.postData()};
    retries++;
    if (!initial) {initial = identity; const response = await route.fetch(); assert.equal(response.status(),201); return route.abort("failed");}
    assert.deepEqual(identity,initial); return route.continue();
  });
  const link = page.locator("#link-create");
  await link.getByLabel("Ad",{exact:true}).selectOption({index:1});
  await link.getByLabel("Destination URL",{exact:true}).fill("https://shop.merchant.com/product?a=1&a=2#detail");
  await link.getByLabel("Placement",{exact:true}).fill("Social");
  await link.getByRole("button",{name:"Create tracking link",exact:true}).click();
  await page.getByRole("button",{name:"Retry the same request",exact:true}).click();
  await page.locator("#links-list a").waitFor();
  assert.equal(retries,2); assert.equal(await page.locator("#links-list a").count(),1);
  await page.unroute("**/v1/links");
  assert.equal(await page.evaluate(() => window.injected),undefined);
  stage = "catalog edits and tracked browser navigation";
  await page.locator("#ads-list").getByLabel("Advertised product reference (optional)",{exact:true}).fill("P2");
  await page.locator("#ads-list").getByRole("button",{name:"Save changes",exact:true}).click();
  await page.waitForFunction(() => document.getElementById("ads-list").textContent.includes("Product reference: P2"));
  const popupPromise = page.waitForEvent("popup"); await page.locator("#links-list a").click(); const landing = await popupPromise;
  await landing.waitForURL(url => url.hostname === "shop.merchant.com");
  const target = new URL(landing.url());
  assert.match(target.searchParams.get("ob_click"),/^[0-9a-f-]{36}$/);
  assert.deepEqual(target.searchParams.getAll("a"),["1","2"]); assert.equal(target.hash,"#detail");
  await landing.close();
  await page.locator("#links-list").getByRole("button",{name:"Disable",exact:true}).click();
  await page.locator("#links-list").getByRole("button",{name:"Enable",exact:true}).waitFor();
  stage = "public installation without server credentials";
  await page.getByLabel("Installation name",{exact:true}).fill("Website");
  await page.getByLabel("Verified domain",{exact:true}).selectOption({label:"shop.merchant.com"});
  await page.getByRole("button",{name:"Add installation",exact:true}).click();
  await page.getByRole("button",{name:"Disable installation",exact:true}).waitFor();
  assert.ok(!(await page.locator("#installations-list").innerText()).includes("ak_"));
  stage = "secret shown once and metadata-only lists";
  await page.getByLabel("Key label",{exact:true}).fill("Backend");
  await page.getByLabel("Paid orders, refunds and cancellations",{exact:true}).check();
  await page.getByRole("button",{name:"Create API key",exact:true}).click();
  await page.getByRole("heading",{name:"Copy this server API key now"}).waitFor();
  const secret = await page.locator("#setup-result code").textContent();
  assert.ok(/^ak_[A-Za-z0-9_-]{43}$/.test(secret));
  assert.ok(!(await page.locator("#credentials-list").innerText()).includes(secret));
  await page.getByRole("button",{name:"I have saved the key",exact:true}).click();
  assert.ok(!(await page.locator("body").textContent()).includes(secret));
  stage = "rotation and revocation";
  await page.getByLabel("Rotation overlap in seconds",{exact:true}).fill("0");
  await page.getByRole("button",{name:"Rotate key",exact:true}).click();
  await page.getByRole("heading",{name:"Copy this server API key now"}).waitFor();
  assert.ok((await page.locator("#setup-result code").textContent()) !== secret);
  await page.getByRole("button",{name:"I have saved the key",exact:true}).click();
  await page.getByRole("button",{name:"Revoke key",exact:true}).last().click();
  await page.waitForFunction(() => document.getElementById("credentials-list").querySelectorAll("button").length===2);
  stage = "installation and domain status";
  await page.getByRole("button",{name:"Disable installation",exact:true}).click();
  await page.getByRole("button",{name:"Enable installation",exact:true}).waitFor();
  await page.getByRole("button",{name:"Revoke domain",exact:true}).click();
  await page.waitForFunction(() => document.getElementById("domains-list").textContent.includes(": revoked"));
  stage = "live member view";
  await page.evaluate(() => fetch("/fixture/member",{method:"POST"}));
  await page.reload();
  await page.locator("#stores-list button").first().click();
  assert.equal(await page.locator("#setup-readonly").isVisible(),true);
  assert.equal(await page.locator("#credential-create").isVisible(),false);
  assert.equal(await page.locator("#campaign-create").isVisible(),false);
  assert.equal(await page.locator("#links-list form").count(),0);
  assert.equal(await page.getByRole("button",{name:"Revoke key",exact:true}).count(),0);
  assert.ok(!(await page.locator("body").textContent()).includes(secret));
  console.log("PASS: setup and catalog browser journey (12 checks): store forms, escaping, DNS proof, public installation, secret once, rotation/revoke, domain/install status, live member view, campaigns/ads/links, lost-response stable retry, product edit, real tracked browser navigation");
} catch (error) {
  const detail = String(error.message).replace(/ak_[A-Za-z0-9_-]{43}/g,"[redacted]").replaceAll(process.env.ATTRIBUTION_BROWSER_SESSION || "unused", "[redacted]");
  console.error(`FAIL: setup browser stage ${stage}: ${error.name}: ${detail}`);
  console.error("Setup status:", await page?.locator("#setup-status").textContent().catch(() => "unavailable"));
  console.error("Setup error:", await page?.locator("#setup-error p").textContent().catch(() => "unavailable"));
  process.exitCode = 1;
} finally {
  await browser?.close();
  if (merchant) await new Promise(resolve => merchant.close(resolve));
  if (certificateDir) rmSync(certificateDir,{recursive:true,force:true});
}
