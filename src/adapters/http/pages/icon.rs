/// One icon, sized and coloured by `class` exactly as a piece of text would be.
///
/// `aria-hidden` because every call site here is decoration next to a label or carries its own
/// `title` — an icon that is the *only* thing naming a control needs a label on that control, not
/// on the glyph.
pub fn icon(icon: Icon, class: &str) -> String {
    format!(
        r##"<svg class="inline-block shrink-0 {class}" viewBox="0 0 16 16" fill="currentColor" aria-hidden="true">{paths}</svg>"##,
        paths = icon.paths(),
    )
}
